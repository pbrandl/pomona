// Compiles contracts/src/**/*.sol with solc-js (no network needed).
// Outputs:
//   contracts/artifacts/<Name>.json   ABI + bytecode (for tests and deploy)
//   app/core/chain/abi.js             ABIs the app needs (generated, committed)
import solc from 'solc'
import { readFileSync, readdirSync, writeFileSync, mkdirSync, statSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)

function walk (dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.sol') ? [p] : []
  })
}

const sources = {}
for (const file of walk(join(root, 'src'))) {
  sources[relative(root, file)] = { content: readFileSync(file, 'utf8') }
}

const input = {
  language: 'Solidity',
  sources,
  settings: {
    // Paris keeps the bytecode deployable on every EVM chain USDT lives on.
    evmVersion: 'paris',
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } }
  }
}

function findImports (path) {
  try {
    return { contents: readFileSync(require.resolve(path), 'utf8') }
  } catch {
    return { error: 'not found: ' + path }
  }
}

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }))
for (const e of out.errors || []) console.error(e.formattedMessage)
if ((out.errors || []).some((e) => e.severity === 'error')) process.exit(1)

mkdirSync(join(root, 'artifacts'), { recursive: true })
const artifacts = {}
for (const [file, contracts] of Object.entries(out.contracts)) {
  if (!file.startsWith('src/')) continue
  for (const [name, c] of Object.entries(contracts)) {
    artifacts[name] = { contractName: name, abi: c.abi, bytecode: '0x' + c.evm.bytecode.object }
    writeFileSync(join(root, 'artifacts', `${name}.json`), JSON.stringify(artifacts[name], null, 2))
    console.log('compiled', name)
  }
}

// The app only needs the ABIs of the production contracts plus a minimal ERC-20.
const abis = {
  PomonaRound: artifacts.PomonaRound.abi,
  PomonaFactory: artifacts.PomonaFactory.abi,
  ERC20: artifacts.MockUSDT.abi.filter((f) => f.name !== 'mint')
}
const target = join(root, '..', 'app', 'core', 'chain', 'abi.js')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, '// Generated by contracts/scripts/build.js. Do not edit by hand.\nexport default ' + JSON.stringify(abis) + '\n')
