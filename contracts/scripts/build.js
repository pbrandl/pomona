// Compiles src/*.sol with solc-js (no network needed) into artifacts/*.json.
import solc from 'solc'
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)

const sources = {}
for (const f of readdirSync(join(root, 'src'))) {
  if (f.endsWith('.sol')) sources[`src/${f}`] = { content: readFileSync(join(root, 'src', f), 'utf8') }
}

const input = {
  language: 'Solidity',
  sources,
  settings: {
    evmVersion: 'paris',
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } }
  }
}

function findImports (path) {
  try {
    return { contents: readFileSync(require.resolve(path), 'utf8') }
  } catch {
    return { error: 'not found: ' + path }
  }
}

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }))
const errors = (out.errors || []).filter(e => e.severity === 'error')
for (const e of out.errors || []) console.error(e.formattedMessage)
if (errors.length) process.exit(1)

mkdirSync(join(root, 'artifacts'), { recursive: true })
for (const [file, contracts] of Object.entries(out.contracts)) {
  if (!file.startsWith('src/')) continue
  for (const [name, c] of Object.entries(contracts)) {
    writeFileSync(join(root, 'artifacts', `${name}.json`),
      JSON.stringify({ contractName: name, abi: c.abi, bytecode: '0x' + c.evm.bytecode.object }, null, 2))
    console.log('compiled', name)
  }
}

// The app ships the ABIs it needs as an ES module.
const abis = {}
for (const n of ['PomonaRound', 'PomonaFactory', 'MockUSDT']) {
  abis[n] = JSON.parse(readFileSync(join(root, 'artifacts', n + '.json'))).abi
}
writeFileSync(join(root, '..', 'app', 'core', 'abi.js'),
  '// Generated by contracts/scripts/build.js. Do not edit by hand.\nexport default ' + JSON.stringify(abis) + '\n')
